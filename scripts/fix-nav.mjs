import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Paths
const CASE_STUDIES_DIR = path.resolve(__dirname, '../src/pages/case-studies');
const NAV_OUTPUT = path.resolve(__dirname, '../src/components/CaseStudyNavigation.astro');

// Helper function to extract frontmatter from MDX/MD files
function extractFrontmatter(filePath) {
  const content = fs.readFileSync(filePath, 'utf-8');
  const frontmatterMatch = content.match(/^---\n([\s\S]*?)\n---/);
  
  if (!frontmatterMatch) {
    return null;
  }
  
  const frontmatterText = frontmatterMatch[1];
  const frontmatter = {};
  
  // Simple YAML parsing for our needs
  const lines = frontmatterText.split('\n');
  for (const line of lines) {
    const colonIndex = line.indexOf(':');
    if (colonIndex > 0) {
      const key = line.substring(0, colonIndex).trim();
      let value = line.substring(colonIndex + 1).trim();
      
      // Remove quotes if present
      if (value.startsWith('"') && value.endsWith('"')) {
        value = value.substring(1, value.length - 1);
      }
      
      frontmatter[key] = value;
    }
  }
  
  return frontmatter;
}

// Generate navigation component
function generateNavigation() {
  console.log('🔧 Updating case study navigation...');
  
  // Get all case study files
  const files = fs.readdirSync(CASE_STUDIES_DIR)
    .filter(file => file.endsWith('.md') || file.endsWith('.mdx'))
    .filter(file => file !== 'index.astro');
  
  const caseStudies = [];
  
  // Extract frontmatter from each case study
  for (const file of files) {
    const filePath = path.join(CASE_STUDIES_DIR, file);
    const frontmatter = extractFrontmatter(filePath);
    
    if (frontmatter && frontmatter.title && frontmatter.slug) {
      caseStudies.push({
        title: frontmatter.title,
        slug: frontmatter.slug,
        summary: frontmatter.summary || '',
        tags: Array.isArray(frontmatter.tags) ? frontmatter.tags : []
      });
    }
  }
  
  // Sort by title
  caseStudies.sort((a, b) => a.title.localeCompare(b.title));
  
  // Generate the navigation component
  const navComponent = `---
// Auto-generated by fix-nav.mjs
// Do not edit manually - run "npm run nav:update" to regenerate
---

<nav class="case-study-nav" aria-label="Case Studies">
  <div class="nav-container">
    <h2>Case Studies</h2>
    <ul class="case-studies-list">
      ${caseStudies.map(study => `
      <li class="case-study-item">
        <a href="/case-studies/${study.slug}" class="case-study-link">
          <h3 class="case-study-title">${study.title}</h3>
          ${study.summary ? `<p class="case-study-summary">${study.summary}</p>` : ''}
          ${study.tags.length > 0 ? `<div class="case-study-tags">${study.tags.map(tag => `<span class="tag">${tag}</span>`).join('')}</div>` : ''}
        </a>
      </li>
      `).join('')}
    </ul>
  </div>
</nav>

<style>
  .case-study-nav {
    margin: 2rem 0;
  }
  
  .nav-container {
    max-width: 1200px;
    margin: 0 auto;
    padding: 0 1rem;
  }
  
  .case-studies-list {
    list-style: none;
    padding: 0;
    margin: 0;
    display: grid;
    grid-template-columns: repeat(auto-fit, minmax(300px, 1fr));
    gap: 1.5rem;
  }
  
  .case-study-item {
    border: 1px solid var(--q-border);
    border-radius: var(--q-radius-lg);
    overflow: hidden;
    transition: transform 0.2s, box-shadow 0.2s;
  }
  
  .case-study-item:hover {
    transform: translateY(-2px);
    box-shadow: 0 8px 25px rgba(0, 0, 0, 0.15);
  }
  
  .case-study-link {
    display: block;
    padding: 1.5rem;
    text-decoration: none;
    color: inherit;
  }
  
  .case-study-title {
    margin: 0 0 0.5rem 0;
    font-size: 1.25rem;
    font-weight: 600;
    color: var(--q-brand-500);
  }
  
  .case-study-summary {
    margin: 0 0 1rem 0;
    font-size: 0.9rem;
    line-height: 1.5;
    color: #E8EAED;
    opacity: 0.8;
  }
  
  .case-study-tags {
    display: flex;
    flex-wrap: wrap;
    gap: 0.5rem;
  }
  
  .tag {
    background: var(--q-brand-500);
    color: #001018;
    padding: 0.25rem 0.5rem;
    border-radius: var(--q-radius-sm);
    font-size: 0.75rem;
    font-weight: 500;
  }
  
  @media (max-width: 768px) {
    .case-studies-list {
      grid-template-columns: 1fr;
    }
  }
</style>
`;
  
  // Write the navigation component
  fs.writeFileSync(NAV_OUTPUT, navComponent);
  console.log(`✅ Generated navigation with ${caseStudies.length} case studies`);
}

// Run the navigation update
generateNavigation();